    private void jButton7ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton7ActionPerformed
        // TODO add your handling code here:
        try {
        String studentId = JOptionPane.showInputDialog(this, "Enter Student ID to check notifications:");

        if (studentId != null && !studentId.trim().isEmpty()) {
            // Check for overdue books
            SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
            Date today = new Date();

            String url = "jdbc:mysql://localhost:3306/lms?zeroDateTimeBehavior=CONVERT_TO_NULL";
            String user = "root";
            String password = "";

            try (Connection conn = DriverManager.getConnection(url, user, password);
                 Statement stmt = conn.createStatement()) {

                ResultSet rs = stmt.executeQuery("SELECT * FROM bookissue WHERE StudentID='" + studentId + "'");
                boolean hasOverdue = false;

                while (rs.next()) {
                    Date returnDate = sdf.parse(rs.getString("Returndate")); // Note the correct column name

                    if (today.after(returnDate)) {
                        long overdueDays = TimeUnit.DAYS.convert(
                                today.getTime() - returnDate.getTime(), TimeUnit.MILLISECONDS);
                        int fine = (int) overdueDays * 50;

                        new OverdueNotification(this, studentId, (int) overdueDays, fine).setVisible(true);
                        hasOverdue = true;
                    }
                }

                if (!hasOverdue) {
                    JOptionPane.showMessageDialog(this, "No overdue books found for this student.");
                }

            } catch (Exception e) {
                e.printStackTrace();
                JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage());
            }
        } else {
            JOptionPane.showMessageDialog(this, "Student ID cannot be empty.");
        }

    } catch (HeadlessException e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
    }//GEN-LAST:event_jButton7ActionPerformed

