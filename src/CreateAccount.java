    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String User_id = jTextField1.getText();
        String Username = jTextField3.getText();
        String Password = jPasswordField1.getText();
        String role = (String) jComboBox1.getSelectedItem();
        
        
        // Database connection parameters
    String url = "jdbc:mysql://localhost:3306/lms?zeroDateTimeBehavior=CONVERT_TO_NULL";
    String user = "root";
    String password = ""; // Default XAMPP MySQL has no password

    // SQL query for inserting data
    String sql = "INSERT INTO user (User_id, Username, Password, role ) VALUES (?, ?, ?, ?)";

    try (Connection conn = DriverManager.getConnection(url, user, password);
         PreparedStatement stmt = conn.prepareStatement(sql)) {

        // Set parameters in the SQL statement
        stmt.setString(1, User_id);
        stmt.setString(2, Username);
        stmt.setString(3, Password);
        stmt.setString(4, role );
        

        // Execute the query
        int rowsInserted = stmt.executeUpdate();
        
        // Show confirmation message
        if (rowsInserted > 0) {
            JOptionPane.showMessageDialog(this, "Student record saved successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
        } else {
            JOptionPane.showMessageDialog(this, "Error saving student record.", "Error", JOptionPane.ERROR_MESSAGE);
        }

    } catch (Exception e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }
                                            

    
                            
    }//GEN-LAST:event_jButton1ActionPerformed

