private void loadReturnedBooks() {
    DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
    model.setRowCount(0); // Clear old data

    try (Connection conn = DriverManager.getConnection(DB_URL, DB_USER, DB_PASS)) {
        String sql = "SELECT BookID, StudentID, Issuedate , Returndate, overduedays,Finecalculate FROM newbook";
        PreparedStatement ps = conn.prepareStatement(sql);
        ResultSet rs = ps.executeQuery();

        while (rs.next()) {
            String bookId = rs.getString("BookID");
            String student = rs.getString("StudentID");
            String issuedate = rs.getString("Issuedate");
            String returndate = rs.getString("Returndate");
            int daysOverdue = rs.getInt("overduedays");
            int fine = rs.getInt("Finecalculate");

            Object[] row = { bookId, student, issuedate, returndate, daysOverdue, fine };
            model.addRow(row);
        }

    } catch (Exception e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Error loading returned books: " + e.getMessage());
    }
}

