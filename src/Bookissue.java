    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        // During loading or on "Check Status" button
String BookID = jTextField1.getText();
        String StudentID = jTextField2.getText();
        String Title = jTextField3.getText();
        String Author = jTextField4.getText();
        String Publisher = jTextField5.getText();
        String Edition = jTextField6.getText();
        String ISBN = jTextField7.getText();
        String Category = (String) jComboBox1.getSelectedItem();
        String IssueDate = jTextField8.getText();
        String ReturnDate = jTextField9.getText();

        String url = "jdbc:mysql://localhost:3306/lms?zeroDateTimeBehavior=CONVERT_TO_NULL";
        String user = "root";
        String password = ""; // Default password

        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
        Date today = new Date();

        try (Connection conn = DriverManager.getConnection(url, user, password)) {
            // 1. Check for overdue books before issuing new one
            String checkSql = "SELECT * FROM bookissue WHERE StudentID=?";
            try (PreparedStatement checkStmt = conn.prepareStatement(checkSql)) {
                checkStmt.setString(1, StudentID);
                ResultSet rs = checkStmt.executeQuery();
                while (rs.next()) {
                    Date returnDate = sdf.parse(rs.getString("Returndate"));
                    if (today.after(returnDate)) {
                        long overdueDays = TimeUnit.DAYS.convert(today.getTime() - returnDate.getTime(), TimeUnit.MILLISECONDS);
                        int fine = (int) overdueDays * 10;
                        new OverdueNotification(this, StudentID, (int) overdueDays, fine).setVisible(true);
                    }
                }
            }

            // 2. Insert book issue record
            String insertSql = "INSERT INTO bookissue (BookID, StudentID, Title, Author, Publisher, Edition, ISBN, Category, Issuedate, Returndate) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)";
            try (PreparedStatement insertStmt = conn.prepareStatement(insertSql)) {
                insertStmt.setString(1, BookID);
                insertStmt.setString(2, StudentID);
                insertStmt.setString(3, Title);
                insertStmt.setString(4, Author);
                insertStmt.setString(5, Publisher);
                insertStmt.setString(6, Edition);
                insertStmt.setString(7, ISBN);
                insertStmt.setString(8, Category);
                insertStmt.setString(9, IssueDate);
                insertStmt.setString(10, ReturnDate);

                int rowsInserted = insertStmt.executeUpdate();
                if (rowsInserted > 0) {
                    JOptionPane.showMessageDialog(this, "Request was successful!", "Success", JOptionPane.INFORMATION_MESSAGE);
                } else {
                    JOptionPane.showMessageDialog(this, "Error saving student record.", "Error", JOptionPane.ERROR_MESSAGE);
                }
            }

        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
        
    }//GEN-LAST:event_jButton1ActionPerformed

